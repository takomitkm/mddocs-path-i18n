"""Small shared helpers: path normalisation, text IO, glob compilation.

Everything inside pathmap is a POSIX-style relative path ("dir/sub/file.md",
forward slashes).  OS-specific separators only appear at the IO boundary
(os.path.join / os.walk), never in comparison keys.
"""

from __future__ import annotations

import os
import posixpath
import re

TEXT_ENCODING = "utf-8"
SENTINEL = ".pathmap-generated"
SENTINEL_TEXT = "generated by pathmap -- wiped and rewritten on every apply\n"


def posix(path: str) -> str:
    """Forward slashes, no leading "./"."""
    p = str(path).replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    return p


def key(rel: str) -> str:
    """Comparison key: forward slashes, trimmed, case-folded.

    Case folding is deliberate: the same map has to work from a Windows
    checkout (case insensitive) and a Linux CI job (case sensitive), and a
    translation list that only matches on one of them is worse than useless.
    """
    p = posix(rel).strip()
    while p.startswith("./"):
        p = p[2:]
    return p.strip("/").casefold()


def join_rel(*parts: str) -> str:
    """Join vault-relative parts, dropping empties, without resolving ".."."""
    keep = [p for p in parts if p not in ("", ".", None)]
    return posixpath.join(*keep) if keep else ""


def resolve_rel(base_dir: str, target: str) -> str:
    """Resolve a relative link target against the directory it appears in."""
    t = posix(target)
    if t.startswith("/"):
        return posixpath.normpath(t.lstrip("/"))
    joined = posixpath.join(base_dir, t) if base_dir else t
    return posixpath.normpath(joined)


def read_text(path: str) -> str:
    """Read UTF-8, tolerating (and dropping) a BOM."""
    with open(path, "rb") as fh:
        data = fh.read()
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return data.decode(TEXT_ENCODING)


def write_text(path: str, text: str) -> None:
    """Write UTF-8 with LF endings and no BOM."""
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding=TEXT_ENCODING, newline="\n") as fh:
        fh.write(text)


def glob_to_regex(pattern: str) -> "re.Pattern[str]":
    """Compile a path glob: ``*`` stays inside one segment, ``**`` crosses.

    Supported: ``*``, ``**``, ``**/``, ``?`` and ``[abc]``.  Matching is
    case-insensitive and always anchored.
    """
    pat = posix(pattern).strip().strip("/")
    out: list[str] = []
    i = 0
    while i < len(pat):
        ch = pat[i]
        if ch == "*":
            if pat[i : i + 2] == "**":
                if pat[i : i + 3] == "**/":
                    out.append("(?:.*/)?")
                    i += 3
                else:
                    out.append(".*")
                    i += 2
            else:
                out.append("[^/]*")
                i += 1
        elif ch == "?":
            out.append("[^/]")
            i += 1
        elif ch == "[":
            end = pat.find("]", i + 1)
            if end == -1:
                out.append(re.escape(ch))
                i += 1
            else:
                out.append(pat[i : end + 1])
                i = end + 1
        else:
            out.append(re.escape(ch))
            i += 1
    return re.compile("^" + "".join(out) + "$", re.IGNORECASE)


def ancestors(rel: str) -> list[str]:
    """"a/b/c.md" -> ["a", "a/b"] (the path itself is not included)."""
    parts = posix(rel).split("/")
    return ["/".join(parts[:i]) for i in range(1, len(parts))]


def adjust_extension(original: str, name: str) -> str:
    """Keep the original file extension unless the new name already carries it.

    "bitproc.md" + "位流生产" -> "位流生产.md";  "bitproc.md" + "位流生产.md" unchanged;
    "pic one.png" + "示意图" -> "示意图.png".
    """
    ext = os.path.splitext(original)[1]
    if ext and not name.lower().endswith(ext.lower()):
        return name + ext
    return name


def is_markdown(rel: str) -> bool:
    return posix(rel).lower().endswith(".md")


def has_hidden_segment(rel: str) -> bool:
    return any(part.startswith(".") for part in posix(rel).split("/") if part)